const MockKnowledge = {
    docs()     { return MockDB.all('docs'); },
    byId(id)   { return MockDB.byId('docs', id); },
    typeLabel(k) { const t = DOC_TYPES.find(x => x.key === k); return t ? t.label : k; },

    byStatus(s) { return s === 'all' ? this.docs() : this.docs().filter(d => d.status === s); },

    /** กฎที่อ้างอิงเอกสารฉบับนี้ */
    rulesFor(docId) { return MockRules.all().filter(r => r.doc_id === docId); },

    /** ค้นคำตอบแบบง่าย — จับคำสำคัญร่วม */
    search(q) {
        const kw = (q || '').trim().toLowerCase();
        if (!kw) return null;
        let best = null, bestScore = 0;
        MOCK_QA.forEach(a => {
            const words = kw.split(/\s+/).filter(w => w.length > 1);
            const score = words.filter(w => a.q.toLowerCase().includes(w)).length;
            if (score > bestScore) { bestScore = score; best = a; }
        });
        /* ไม่มีคำไหนตรงเลย → ตอบว่าหลักฐานไม่พอ แทนการเดา (BR-06) */
        return bestScore ? best : MOCK_QA.find(a => a.insufficient);
    },
};

